def _normalize_subject(subject: str) -> str:
    return str(subject or "").strip()


def infer_subject_family(subject: str) -> str:
    """Return a coarse subject family id used for prompt/knowledge routing."""

    s = _normalize_subject(subject)
    if not s:
        return "generic"

    if "数学" in s or s.lower() in {"math", "mathematics"}:
        return "math"
    if "物理" in s or "physics" in s.lower():
        return "physics"
    if "化学" in s or "chem" in s.lower():
        return "chemistry"
    if "生物" in s or "biology" in s.lower():
        return "biology"
    if "语文" in s or "中文" in s or "chinese" in s.lower():
        return "chinese"
    if "英语" in s or "english" in s.lower():
        return "english"
    return "generic"


